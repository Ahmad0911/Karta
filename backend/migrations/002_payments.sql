-- Server-side prices and orders, so the server (never the browser) decides what a customer owes.

CREATE TABLE listings (
  id           TEXT PRIMARY KEY,
  vendor_id    TEXT NOT NULL REFERENCES users(id),
  name         TEXT NOT NULL,
  price_kobo   INTEGER NOT NULL CHECK (price_kobo > 0),
  stock        INTEGER NOT NULL CHECK (stock >= 0),
  status       TEXT NOT NULL CHECK (status IN ('draft','live','paused')),
  updated_at   TEXT NOT NULL
);

CREATE TABLE orders (
  id             TEXT PRIMARY KEY,
  number         TEXT NOT NULL UNIQUE,
  customer_id    TEXT NOT NULL REFERENCES users(id),
  status         TEXT NOT NULL CHECK (status IN ('awaiting_payment','paid','cancelled','refunded')),
  ship_state     TEXT NOT NULL,
  ship_city      TEXT NOT NULL,
  ship_address   TEXT NOT NULL,
  subtotal_kobo  INTEGER NOT NULL,
  delivery_kobo  INTEGER NOT NULL,
  total_kobo     INTEGER NOT NULL,
  refunded_kobo  INTEGER NOT NULL DEFAULT 0,
  created_at     TEXT NOT NULL,
  paid_at        TEXT
);
CREATE INDEX orders_customer ON orders(customer_id, created_at);

CREATE TABLE order_lines (
  id               TEXT PRIMARY KEY,
  order_id         TEXT NOT NULL REFERENCES orders(id),
  listing_id       TEXT NOT NULL REFERENCES listings(id),
  vendor_id        TEXT NOT NULL REFERENCES users(id),
  name             TEXT NOT NULL,
  unit_price_kobo  INTEGER NOT NULL,
  qty              INTEGER NOT NULL CHECK (qty > 0)
);

CREATE TABLE payments (
  reference        TEXT PRIMARY KEY,                 -- generated by us, sent to Paystack
  order_id         TEXT NOT NULL REFERENCES orders(id),
  provider         TEXT NOT NULL,
  amount_kobo      INTEGER NOT NULL,                 -- what WE expect to be paid
  paid_amount_kobo INTEGER,
  status           TEXT NOT NULL CHECK (status IN ('pending','paid','failed','abandoned')),
  created_at       TEXT NOT NULL,
  paid_at          TEXT
);
CREATE INDEX payments_order ON payments(order_id);

-- A provider event is processed once, however many times it is delivered.
CREATE TABLE payment_events (
  id           TEXT PRIMARY KEY,                     -- e.g. "charge.success:<reference>"
  received_at  TEXT NOT NULL
);

CREATE TABLE refunds (
  id           TEXT PRIMARY KEY,
  reference    TEXT NOT NULL REFERENCES payments(reference),
  amount_kobo  INTEGER NOT NULL CHECK (amount_kobo > 0),
  status       TEXT NOT NULL CHECK (status IN ('pending','completed','failed')),
  note         TEXT NOT NULL,
  created_by   TEXT NOT NULL REFERENCES users(id),
  created_at   TEXT NOT NULL
);
