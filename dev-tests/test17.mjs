// Search engine
let pass = 0, fail = 0
const ok = (n, c, x = '') => { if (c) { pass++; console.log('  ✓', n) } else { fail++; console.log('  ✗ FAIL:', n, x) } }
const { products } = await import('@/data/products')
const { search, suggest, facets, extractPrice, editDistance, stem } = await import('@/modules/catalog/search')
const names = (r) => r.products.map(p => p.name)
const first = (q, f = {}) => search(products, { q, ...f }).products[0]?.name
const has = (q, re, f = {}) => search(products, { q, ...f }).products.some(p => re.test(p.name))
const only = (q, re, f = {}) => { const r = search(products, { q, ...f }); return r.mode === 'exact' && r.products.length > 0 && r.products.every(p => re.test(p.name)) }

console.log('\nMeaning, not just spelling')
ok('"sofa" finds the sofa first', /Sofa/.test(first('sofa')), first('sofa'))
ok('"couch" finds sofas (synonym)', has('couch', /Sofa/))
ok('"settee" finds sofas (synonym)', has('settee', /Sofa/))
ok('"closet" finds the wardrobe (synonym)', has('closet', /Wardrobe/))
ok('"wardrobes" finds it too (plural)', has('wardrobes', /Wardrobe/))
ok('"sofas" (plural) finds the sofa', has('sofas', /Sofa/))
ok('"lighting" finds the lamp through its category', has('lighting', /Lamp/))
ok('"desk" finds the executive desk first', /Desk/.test(first('desk')), first('desk'))

console.log('\nTypos')
ok('"sofaa" still finds the sofa', has('sofaa', /Sofa/))
ok('"dinning table" finds the dining table', /Dining Table/.test(first('dinning table')), first('dinning table'))
ok('"wardrob" (half-typed) finds the wardrobe', has('wardrob', /Wardrobe/))
ok('"bouclé" and "boucle" are the same', has('boucle', /Sofa/) && has('bouclé', /Sofa/))
ok('a swapped pair is a single slip: "sofa" ← "sfoa"', has('sfoa', /Sofa/))
ok('edit distance counts a swap as one', editDistance('sfoa', 'sofa', 2) === 1)

console.log('\nEvery word counts')
ok('"oak bed" finds the oak bed only', only('oak bed', /Oak Bed/), JSON.stringify(names(search(products, { q: 'oak bed' }))))
ok('"walnut desk" finds the desk', /Desk/.test(first('walnut desk')))
ok('"linen" matches materials too (wardrobe and lamp shade)', has('linen', /Wardrobe/) && has('linen', /Lamp/))
ok('words in any order work', has('table dining', /Dining Table/))
ok('"Ade" finds the maker’s pieces', has('ade woodworks', /Oak Bed|Sofa|Table|Wardrobe|Desk|Chair|Lamp|Vase/))
ok('the name outranks a mention elsewhere', /Lounge Chair/.test(first('lounge chair')), first('lounge chair'))

console.log('\nPrices in words')
const pr = extractPrice('bed under 600k')
ok('"under 600k" → max ₦600,000 and the word "under" is not searched', pr.max === 600000 && !/under/.test(pr.text))
ok('"over ₦300,000" → min 300000', extractPrice('sofa over ₦300,000').min === 300000)
ok('"between 200k and 500k"', (() => { const x = extractPrice('table between 200k and 500k'); return x.min === 200000 && x.max === 500000 })())
ok('"1.5m" works', extractPrice('under 1.5m').max === 1500000)
ok('"under 200k" shows only things ≤ ₦200,000', search(products, { q: 'under 200k' }).products.every(p => p.price <= 200000) && search(products, { q: 'under 200k' }).products.length > 0)
ok('"bed under 300k" is empty (the bed is ₦540,000)', search(products, { q: 'bed under 300k' }).products.length === 0 || search(products, { q: 'bed under 300k' }).mode !== 'exact')
ok('"bed under 600k" finds the bed', has('bed under 600k', /Bed Frame/))
ok('an explicit filter beats the words', search(products, { q: 'under 100k', max: 50000 }).products.every(p => p.price <= 50000))

console.log('\nWhen nothing matches exactly')
const rel = search(products, { q: 'oak sofa' })
ok('partial matches are offered as "related", never an empty page', rel.mode === 'related' && rel.products.length > 0, rel.mode)
ok('related results put the better match first', /Sofa|Oak/.test(rel.products[0].name))
const none = search(products, { q: 'zzzzqx' })
ok('gibberish returns nothing, calmly', none.mode === 'none' && none.products.length === 0)
const dym = search(products, { q: 'wardrbe lampp' })
ok('a "did you mean" is offered for bad spelling', !!dym.didYouMean || dym.products.length > 0, JSON.stringify(dym.didYouMean))
ok('empty search = everything', search(products, { q: '' }).products.length === products.length)
ok('stop-words are ignored ("a sofa for the living room")', has('a sofa for the living room', /Sofa/))

console.log('\nFilters and sorting')
ok('room filter', search(products, { q: '', room: 'bedroom' }).products.every(p => p.room === 'bedroom'))
ok('category filter', search(products, { q: '', category: 'tables' }).products.every(p => p.categoryId === 'tables'))
ok('price filter', search(products, { q: '', min: 100000, max: 500000 }).products.every(p => p.price >= 100000 && p.price <= 500000))
ok('sorts low to high', (() => { const l = search(products, { q: '', sort: 'price-asc' }).products; return l.every((p, i) => i === 0 || l[i - 1].price <= p.price) })())
ok('sorts high to low', (() => { const l = search(products, { q: '', sort: 'price-desc' }).products; return l.every((p, i) => i === 0 || l[i - 1].price >= p.price) })())
ok('filters combine with words', search(products, { q: 'table', room: 'dining' }).products.every(p => p.room === 'dining'))
ok('in-stock only', search(products, { q: '', inStock: true }).products.every(p => p.inStock))

console.log('\nFacets and suggestions')
const fc = facets(products, 'oak')
ok('facets count what the words found', fc.rooms.reduce((n, r) => n + r.count, 0) === search(products, { q: 'oak' }).products.length)
ok('facet price range matches the results', fc.priceMin <= fc.priceMax)
const sg = suggest(products, 'sof')
ok('typing "sof" suggests the sofa', sg.products.some(p => /Sofa/.test(p.name)) && sg.categories.some(c => c.id === 'sofas'))
ok('one letter suggests nothing (no noise)', suggest(products, 's').products.length === 0)
ok('stems are sensible', stem('shelves') === 'shelf' && stem('wardrobes') === 'wardrobe' && stem('glass') === 'glass' && stem('boxes') === 'box')

console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
